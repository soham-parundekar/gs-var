def table5() -> str:
    """Sizing check: disclosed sleeve VaR against what the book achieves."""
    errors = _read("calibration_error_by_year.csv")

    pretty = {
        "interest_rates": "Rates",
        "equity_prices": "Equity",
        "currency_rates": "Currency",
        "commodity_prices": "Commodity",
    }
    order = list(pretty)
    wide = errors.pivot(index="year", columns="category", values="error_pct")[order]
    disclosed = errors.pivot(index="year", columns="category", values="disclosed_usd_mm")[order]

    worst = errors.error_pct.abs().max()
    if worst > 1e-9:
        raise SystemExit(
            f"sizing error of {worst:.3e}% is too large to call exact; the "
            f"homogeneity claim in Section 4 would not hold"
        )

    rows = []
    for year in wide.index:
        cells = [str(int(year))]
        for category in order:
            cells.append(f"{disclosed.loc[year, category]:.0f}")
        cells.append(f"{wide.loc[year].abs().max():.2e}")
        rows.append(" & ".join(cells) + r" \\")

    return _preamble("calibration_error_by_year.csv", "") + "\n" + "\n".join([
        r"\begin{table}[tbp]",
        r"\centering",
        r"\small",
        r"\caption{Sizing check: the disclosed sleeve targets, and the largest "
        r"error the calibration leaves behind}",
        r"\label{tab:sizing}",
        r"\begin{tabular}{@{}lrrrrr@{}}",
        r"\toprule",
        r" & \multicolumn{4}{c}{Disclosed target (\$mm)} & Largest error \\",
        r"\cmidrule(lr){2-5}",
        r"Year & " + " & ".join(pretty[c] for c in order) + r" & (\% of target) \\",
        r"\midrule",
        "\n".join(rows),
        r"\bottomrule",
        r"\end{tabular}",
        rf"\notetext{{Targets are Goldman's disclosed average daily VaR by "
        rf"category, as first reported. The final column is the largest "
        rf"absolute sizing error across the four sleeves in that year, as a "
        rf"percentage of target. Across all {len(errors)} sleeve-years the "
        rf"largest error is {worst:.2e}\%, which is floating-point noise: the "
        rf"calibration is exact, as Equation~\eqref{{eq:homogeneity}} requires, "
        rf"and this table verifies that claim rather than reporting a "
        rf"convergence result.}}",
        r"\end{table}",
    ]) + "\n"


