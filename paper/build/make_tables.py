def table10() -> str:
    """The two disclosed measures of the ratio, against their proxy analogues.

    The columns were chosen after peer review. An earlier version reported a
    regression trend and its p-value; the proxy series is built from
    overlapping five-year windows, so those p-values assumed an independence
    the data does not have. What replaces them is descriptive movement and the
    lag-1 autocorrelation, which is the statistic that actually distinguishes
    a series that reverts from one that drifts, and which needs no model.
    """
    cats = list(CATEGORIES)

    def disclosed_share(name: str) -> pd.Series:
        d = _read(name)
        first = d[d.year == d.source_fiscal_year].sort_values("year").set_index("year")
        return -first.diversification_effect / first[cats].sum(axis=1) * 100.0

    average_daily = disclosed_share("gs_var_average_daily.csv")
    period_end = disclosed_share("gs_var_period_end.csv")
    proxy_average = _read("diversification_comparison.csv").set_index("year").model_fixed_pct

    book = pd.read_csv(DATA_ROOT / "var_fixed_book_daily.csv", parse_dates=["date"])
    book = book.set_index("date")
    ratio = -book.diversification_effect / book.sum_category_var * 100.0
    proxy_period_end = ratio.groupby(ratio.index.year).last()

    series = [
        ("Goldman, average daily", average_daily),
        ("Goldman, period-end", period_end),
        ("Proxy, average daily", proxy_average),
        ("Proxy, final day of year", proxy_period_end),
    ]

    rows = []
    for i, (label, s) in enumerate(series):
        values = s.to_numpy(dtype=float)
        rho = float(np.corrcoef(values[:-1], values[1:])[0, 1])
        halves = values[5:].mean() - values[:5].mean()
        if i == 2:
            rows.append(r"\addlinespace")
        rows.append(" & ".join([
            label,
            f"{values.mean():.2f}",
            f"{values.std(ddof=1):.2f}",
            f"{values.min():.1f}--{values.max():.1f}",
            f"{halves:+.1f}",
            f"{rho:+.2f}",
        ]) + r" \\")

    return _preamble("gs_var_average_daily.csv, gs_var_period_end.csv and "
                     "var_fixed_book_daily.csv", "") + "\n" + "\n".join([
        r"\begin{table}[tbp]",
        r"\centering",
        r"\small",
        r"\caption{Amplitude and persistence: the two disclosed measures of the "
        r"diversification effect against their proxy analogues}",
        r"\label{tab:amplitude}",
        r"\begin{tabular}{@{}lrrlrr@{}}",
        r"\toprule",
        r" & & Std. & & Change, first & Lag-1 \\",
        r"Series & Mean & dev. & Range & half to second & autocorr. \\",
        r"\midrule",
        "\n".join(rows),
        r"\bottomrule",
        r"\end{tabular}",
        r"\notetext{All figures are the diversification effect as a percentage "
        r"of summed category VaR across the ten fiscal years, so each column "
        r"rests on ten observations and none is precisely estimated. "
        r"\emph{Change} is the mean of 2021--2025 less the mean of 2016--2020. "
        r"\emph{Lag-1 autocorr.} is the correlation between consecutive annual "
        r"values: negative indicates a series that returns toward its mean, "
        r"positive one that carries its level forward. Neither disclosed "
        r"series shows positive persistence --- the average daily series is "
        r"$-0.47$ and the period-end series is essentially zero --- while both "
        r"proxy series sit near $+0.9$. That contrast, rather than any "
        r"difference in spread, is what Section~\ref{sec:results} rests on. "
        r"No trend test is reported: the proxy's annual values are computed "
        r"from overlapping five-year windows and share about 82\% of their "
        r"scenario set with their neighbours, so a regression on them would "
        r"understate its own standard errors.}",
        r"\end{table}",
    ]) + "\n"


