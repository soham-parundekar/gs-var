    sd = disclosed.std()

    level_gap = abs(percentile.mean_diversification_pct.iloc[0]
                    - percentile.mean_diversification_pct.iloc[1])
    var_gap = (abs(percentile.mean_var.iloc[0] - percentile.mean_var.iloc[1])
               / percentile.mean_var.mean() * 100.0)
    steady = variants[variants.std_across_years <= sd]
    high = variants[variants.mean_diversification_pct >= 40]

    # Each row: the candidate, the quantity that settles it, the verdict.
    rows = [
        ("Percentile convention",
         rf"Moves VaR by {var_gap:.2f}\% and the mean ratio by {level_gap:.2f} pp",
         "Excluded"),
        ("Convexity in the rate sleeve",
         rf"Full revaluation against duration moves annual VaR by at most "
         rf"{abs(convexity.difference_pct).max():.2f}\%",
         "Excluded"),
        ("Lookback window too short",
         rf"Lengthening 1y$\rightarrow$5y cuts the gap from "
         rf"{windows.loc[252,'std_across_years']:.2f} to "
         rf"{windows.loc[1260,'std_across_years']:.2f} pp, against {sd:.2f}",
         "Right way, insufficient"),
        ("Equal weighting, not Goldman's",
         rf"Swept over 16 decay rates: the steadiest is equal weighting at "
         rf"{grid.std_across_years.min():.2f} pp and every weighted rate is "
         rf"worse, while coverage improves",
         "Refuted"),
        ("Wrong sleeve directions",
         rf"Of 16 configurations, {len(steady)} match the steadiness and peak at "
         rf"{steady.mean_diversification_pct.max():.1f}\%; {len(high)} match the "
         rf"level and bottom out at {high.std_across_years.min():.2f} pp",
         "Excluded"),
        ("Seventeen factors, not 70{,}000",
         "Not testable on public data; biases the level downward, direction on "
         "steadiness unknown",
         "Survives"),
        ("Non-synchronous closes",
         "Depresses measured cross-market correlation; magnitude not estimated",
         "Survives"),
        ("Exposures are managed, not held",
         "Goldman attributes VaR changes to exposure moves in four consecutive "
         "filings; the only candidate whose mechanism produces reversion "
         "rather than drift",
         "Survives"),
    ]

    body = []
    for candidate, quantity, verdict in rows:
        body.append(" & ".join([candidate, quantity, verdict]) + r" \\")

    return _preamble("the robustness and comparison outputs", "") + "\n" + "\n".join([
        r"\begin{table}[tbp]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{5pt}",
        r"\caption{Candidate explanations for the steadiness gap, and what "
        r"settles each}",
        r"\label{tab:candidates}",
        r"\begin{tabularx}{\linewidth}{@{}l Y l@{}}",
        r"\toprule",
        r"Candidate & What settles it & Verdict \\",
        r"\midrule",
        "\n".join(body),
        r"\bottomrule",
        r"\end{tabularx}",
        rf"\notetext{{The disclosed year-to-year standard deviation is "
        rf"{sd:.2f} percentage points; every quantity in the middle column is "
        rf"measured against that. \emph{{Refuted}} is stronger than "
        rf"\emph{{excluded}}: the disclosed weighting was adopted and moved the "
        rf"gap the wrong way. The three surviving candidates are not ranked, "
        rf"because nothing in the frozen evidence ranks them.}}",
        r"\end{table}",
    ]) + "\n"


