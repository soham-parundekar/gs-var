"""Generate the manuscript's table bodies from the frozen research outputs.

The research repository is a separate artefact and is treated as read-only
here: this script reads the CSVs under its ``data/processed`` directory and
writes LaTeX into ``tables/``. Nothing in the pipeline is re-run, and no
number is typed into the manuscript by hand.

The data root defaults to the research repository sitting one level above the
paper, which is the layout in the project directory. Override it with
GSVAR_DATA_ROOT when the two live apart.

Every input is committed except the aligned factor panel, which cannot be
redistributed. Table 3 reads it for one date-span sentence; without it that
table alone is skipped and the exit status fails, so the shortfall is visible
rather than silent.

Usage:
    python build/make_tables.py            # all tables
    python build/make_tables.py table1     # one table
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

PAPER_ROOT = Path(__file__).resolve().parent.parent
DATA_ROOT = Path(
    os.environ.get("GSVAR_DATA_ROOT", PAPER_ROOT.parent / "data" / "processed")
)
TABLE_DIR = PAPER_ROOT / "tables"

CATEGORIES = {
    "interest_rates": "Interest rates",
    "equity_prices": "Equity prices",
    "currency_rates": "Currency rates",
    "commodity_prices": "Commodity prices",
}


class PanelMissing(RuntimeError):
    """Raised when the aligned factor panel is absent.

    The panel is the only input these generators read that the repository does
    not track: it interleaves a commercial source whose terms forbid
    redistribution. Everything else is committed model output, so this is the
    one shortfall a reader can hit after a clean clone, and it is worth
    reporting as itself rather than as a missing file.
    """


def _read(name: str) -> pd.DataFrame:
    path = DATA_ROOT / name
    if not path.exists():
        raise SystemExit(
            f"{path} not found. Point GSVAR_DATA_ROOT at the research "
            f"repository's data/processed directory."
        )
    return pd.read_csv(path)


def _panel_span() -> str:
    """Describe the panel's extent for the note under Table 3.

    Only the span is read from the panel. Every number in the table comes from
    the committed summary, which is why a reader without the panel loses one
    sentence rather than a table.
    """
    path = DATA_ROOT / "factor_moves.csv"
    if not path.exists():
        raise PanelMissing(
            "factor_moves.csv is not tracked, because the aligned panel "
            "carries a commercial source. Rebuild it with "
            "scripts/02_build_factors.py and rerun."
        )
    panel = pd.read_csv(path)
    dates = pd.to_datetime(panel.iloc[:, 0])
    return (f"{len(panel):,} aligned trading days from "
            f"{dates.min():%-d %B %Y} to {dates.max():%-d %B %Y}")


def _preamble(source: str, note: str) -> str:
    return f"% Generated by build/make_tables.py from {source}. Do not edit.\n{note}"


def table1() -> str:
    """Disclosed average daily VaR by category, as first reported."""
    disclosed = _read("gs_var_average_daily.csv")

    # Each 10-K restates the prior year, so most years appear twice. Keep the
    # row from the filing that first reported the year, which is the figure
    # that was not conformed to a later methodology.
    first = disclosed[disclosed.year == disclosed.source_fiscal_year]
    first = first.sort_values("year")

    cats = list(CATEGORIES)
    summed = first[cats].sum(axis=1)
    effect = first["diversification_effect"]
    share = -effect / summed * 100.0

    # The disclosure is an identity, not three independent numbers. If it ever
    # fails to close, the parse is wrong and the table must not be written.
    residual = (first["total"] - summed - effect).abs().max()
    if residual != 0:
        raise SystemExit(f"identity does not close; max residual {residual}")

    rows = []
    for (_, row), total_cat, eff, pct in zip(
        first.iterrows(), summed, effect, share
    ):
        cells = [f"{int(row.year)}"]
        cells += [f"{int(row[c])}" for c in cats]
        cells += [f"{int(total_cat)}", f"{int(eff)}", f"{int(row.total)}",
                  f"{pct:.1f}"]
        rows.append(" & ".join(cells) + r" \\")

    mean_pct = share.mean()
    sd_pct = share.std()
    body = "\n".join(rows)

    note = (
        r"\notetext{In millions of US dollars, except the final column. "
        r"Average daily 95\% one-day Value-at-Risk as reported in the Market "
        r"Risk Management section of each fiscal year's Form 10-K, taken from "
        r"the filing that first reported the year rather than from a later "
        r"filing's restatement. \emph{Summed} is the sum of the four category "
        r"figures and is not itself disclosed. The diversification effect is "
        r"disclosed as a negative number and reproduced with its sign; the "
        r"final column expresses its magnitude as a percentage of the summed "
        r"categories. Total VaR equals the summed categories plus the "
        r"diversification effect in every year, exactly. The percentage "
        rf"averages {mean_pct:.1f} with a standard deviation of {sd_pct:.2f} "
        r"across the ten years.}"
    )

    return (
        _preamble("gs_var_average_daily.csv", "") + "\n"
        + "\n".join([
            r"\begin{table}[tbp]",
            r"\centering",
            r"\caption{Goldman Sachs average daily Value-at-Risk by risk "
            r"category, and the disclosed diversification effect, "
            r"FY2016--FY2025}",
            r"\label{tab:disclosed}",
            r"\begin{tabular}{@{}lrrrrrrrr@{}}",
            r"\toprule",
            r" & \multicolumn{4}{c}{Risk category} & & & & \\",
            r"\cmidrule(lr){2-5}",
            r"Year & Rates & Equities & FX & Commod. & Summed & "
            r"Diversif. & Total & \% of sum \\",
            r"\midrule",
            body,
            r"\bottomrule",
            r"\end{tabular}",
            note,
            r"\end{table}",
        ])
        + "\n"
    )


