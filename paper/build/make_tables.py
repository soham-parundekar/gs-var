def main(argv: list[str]) -> int:
    wanted = argv[1:] or list(TABLES)
    TABLE_DIR.mkdir(exist_ok=True)
    skipped = 0
    for key in wanted:
        if key not in TABLES:
            raise SystemExit(f"unknown table {key!r}; have {sorted(TABLES)}")
        builder, filename = TABLES[key]
        try:
            body = builder()
        except PanelMissing as absent:
            # One missing input should cost one table, not the whole run. The
            # exit status still fails, because the manuscript cannot compile
            # with a table file absent.
            print(f"skipped tables/{filename}: {absent}", file=sys.stderr)
            skipped += 1
            continue
        (TABLE_DIR / filename).write_text(body, encoding="utf-8")
        print(f"wrote tables/{filename}")
    if skipped:
        print(f"{skipped} table(s) not built; the manuscript will not compile "
              f"until they are.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
